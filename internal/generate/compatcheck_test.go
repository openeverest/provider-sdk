const (
	testProvidersCRD     = "providers.core.openeverest.io"
	testBackupClassesCRD = "backupclasses.backup.openeverest.io"
)

func TestCompatCheck(t *testing.T) {
	t.Parallel()

	got := CompatCheck([]string{testProvidersCRD, testBackupClassesCRD})

	assert.Equal(t, `{{- /* Code generated by provider-sdk generate. DO NOT EDIT. */ -}}
{{- /*
Fails the render, before anything is applied, when the OpenEverest in the
cluster does not serve the OpenEverest this chart is built for; see
openeverest.contract.check in _openeverest_contract.tpl. crds lists the CRDs
of the objects OpenEverest interprets that the chart applies.
*/ -}}
{{- include "openeverest.contract.check" (dict
  "root" .
  "stamp" (index .Chart.Annotations "openeverest.io/contract-version")
  "crds" (list "providers.core.openeverest.io" "backupclasses.backup.openeverest.io")
  "object" (dict "apiVersion" "core.openeverest.io/v1alpha1" "kind" "Provider" "crd" "providers.core.openeverest.io" "name" (.Values.provider | default dict).name)
) -}}
`, got)
}

// chartFiles returns a provider chart stamped stamp, with the generated
// helper and check, and the scaffolded Provider and BackupClass templates.
func chartFiles(stamp string) map[string]string {
	return map[string]string{
		"Chart.yaml":                       "apiVersion: v2\nname: provider-x\nversion: 0.1.0\nannotations:\n  openeverest.io/contract-version: \"" + stamp + "\"\n",
		"values.yaml":                      "provider:\n  name: x\n",
		"templates/" + ContractHelperFile:  ContractHelper,
		"templates/" + CompatCheckFile:     CompatCheck([]string{testProvidersCRD}),
		"templates/provider.yaml":          "apiVersion: core.openeverest.io/v1alpha1\nkind: Provider\nmetadata:\n  name: {{ .Values.provider.name }}\n  annotations:\n    {{- include \"openeverest.contract.annotations\" . | nindent 4 }}\n",
		"templates/backupclasses.yaml":     "{{- range $path, $_ := .Files.Glob \"generated/backupclasses/*.yaml\" }}\n---\n{{ $.Files.Get $path }}\n{{- end }}\n",
		"generated/backupclasses/.gitkeep": "",
	}
}

func TestAppliedCRDs(t *testing.T) {
	t.Parallel()

	backupClass := "apiVersion: backup.openeverest.io/v1alpha1\nkind: BackupClass\nmetadata:\n  name: pbm\n"
	tests := map[string]struct {
		changes map[string]string
		want    []string
		wantErr string
	}{
		"Provider only": {
			want: []string{testProvidersCRD},
		},
		"generated BackupClasses": {
			changes: map[string]string{
				"generated/backupclasses/pbm.yaml":  backupClass,
				"generated/backupclasses/pitr.yaml": "apiVersion: backup.openeverest.io/v1alpha1\nkind: BackupClass\nmetadata:\n  name: pitr\n",
			},
			want: []string{testProvidersCRD, testBackupClassesCRD},
		},
		"hand-written classes, sorted after the Provider's": {
			changes: map[string]string{
				"generated/backupclasses/pbm.yaml": backupClass,
				"templates/classes.yaml": "apiVersion: monitoring.openeverest.io/v1alpha1\nkind: MonitoringClass\nmetadata:\n  name: pmm\n" +
					"---\napiVersion: backup.openeverest.io/v1alpha1\nkind: BackupStorageClass\nmetadata:\n  name: swift\n" +
					"---\napiVersion: v1\nkind: ConfigMap\nmetadata:\n  name: other\n",
			},
			want: []string{
				testProvidersCRD,
				testBackupClassesCRD,
				"backupstorageclasses.backup.openeverest.io",
				"monitoringclasses.monitoring.openeverest.io",
			},
		},
		"no Provider rendered": {
			changes: map[string]string{"templates/provider.yaml": ""},
			want:    []string{testProvidersCRD},
		},
		"ClusterInstancePresets": {
			changes: map[string]string{
				"templates/presets.yaml": "apiVersion: core.openeverest.io/v1alpha1\nkind: ClusterInstancePreset\nmetadata:\n  name: small\n",
			},
			want: []string{testProvidersCRD, "clusterinstancepresets.core.openeverest.io"},
		},
		"the objects of subcharts": {
			changes: map[string]string{
				"charts/sub/Chart.yaml":         "apiVersion: v2\nname: sub\nversion: 0.1.0\n",
				"charts/sub/templates/pmm.yaml": "apiVersion: monitoring.openeverest.io/v1alpha1\nkind: MonitoringClass\nmetadata:\n  name: pmm\n",
			},
			want: []string{testProvidersCRD},
		},
		"a check written by another provider-sdk": {
			changes: map[string]string{"templates/" + CompatCheckFile: "{{ include \"openeverest.contract.removed\" . }}\n"},
			want:    []string{testProvidersCRD},
		},
		"a chart that does not render": {
			changes: map[string]string{"templates/bad.yaml": "{{ fail \"broken\" }}\n"},
			wantErr: "rendering the chart to find the objects OpenEverest interprets",
		},
	}
	for name, tt := range tests {
		t.Run(name, func(t *testing.T) {
			t.Parallel()

			files := chartFiles("2.1.0")
			for path, content := range tt.changes {
				if content == "" {
					delete(files, path)
					continue
				}
				files[path] = content
			}
			dir := t.TempDir()
			writeFiles(t, dir, files)

			got, err := appliedCRDs(dir)

			if tt.wantErr != "" {
				require.Error(t, err)
				assert.Contains(t, err.Error(), tt.wantErr)
				return
			}
			require.NoError(t, err)
			assert.Equal(t, tt.want, got)
		})
	}
}

// TestCompatCheckPassesWithoutACluster renders the check the way helm
// template, a client-side dry run or Argo CD do: lookup finds nothing, so
// the check passes whatever the stamp, and renders nothing.
func TestCompatCheckPassesWithoutACluster(t *testing.T) {
	t.Parallel()

	for _, stamp := range []string{"2.1.0", "99.0.0", "2.0.0-alpha.1.dev", "", "v2"} {
		t.Run(stamp, func(t *testing.T) {
			t.Parallel()

			dir := t.TempDir()
			writeFiles(t, dir, chartFiles(stamp))

			objects, err := chartrender.Render(dir)

			require.NoError(t, err)
			require.Len(t, objects, 1)
			assert.Equal(t, "templates/provider.yaml", objects[0].Source)
		})
	}
}

func TestRunWritesTheCompatCheck(t *testing.T) {
	t.Parallel()

	chartDir := t.TempDir()
	files := chartFiles("2.0.0")
	delete(files, "templates/"+CompatCheckFile)
	delete(files, "templates/"+ContractHelperFile)
	writeFiles(t, chartDir, files)
	defDir := writeDefinition(t, `
componentTypes:
  mongod:
    versions:
      - version: "8.0.12-4"
        image: percona/psmdb:8.0.12-4
`)
	writeFiles(t, filepath.Join(defDir, "backupclasses", "pbm"), map[string]string{
		"class.yaml": "backupStorageClasses:\n  - name: s3\n    authModes: [AccessKey]\n",
	})

	require.NoError(t, Run(Options{DefinitionDir: defDir, ChartDir: chartDir, ContractVersion: "2.1.0"}))

	check, err := os.ReadFile(filepath.Join(chartDir, "templates", CompatCheckFile))
	require.NoError(t, err)
	assert.Equal(t, CompatCheck([]string{testProvidersCRD, testBackupClassesCRD}), string(check))
	helper, err := os.ReadFile(filepath.Join(chartDir, "templates", ContractHelperFile))
	require.NoError(t, err)
	assert.Equal(t, ContractHelper, string(helper))
}
