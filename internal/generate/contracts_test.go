const (
	contractPath = "example.com/pmm/api"

	contractDestinationSchema = `# Code generated by classgen. DO NOT EDIT.
type: object
required: [url]
properties:
  url:
    type: string
    pattern: ^https?://[^/?#@]+/?$
`
	contractInstanceSchema = `type: object
properties:
  resources:
    type: object
    additionalProperties: false
    properties:
      limits:
        type: object
        additionalProperties:
          x-kubernetes-int-or-string: true
`
)

// contractFiles are the files of a well-formed contract module.
func contractFiles() map[string]string {
	return map[string]string{
		"go.mod":                  "module " + contractPath + "\n\ngo 1.27.1\n",
		destinationParametersFile: contractDestinationSchema,
		instanceParametersFile:    contractInstanceSchema,
	}
}

func writeFiles(t *testing.T, dir string, files map[string]string) {
	t.Helper()
	for name, content := range files {
		path := filepath.Join(dir, name)
		require.NoError(t, os.MkdirAll(filepath.Dir(path), 0o750))
		require.NoError(t, os.WriteFile(path, []byte(content), 0o600))
	}
}

// writeProviderWithContract writes a provider module that requires the
// contract module, replaced by a local copy holding contract, and returns
// its definition directory, whose monitoring.yaml is monitoringYAML.
func writeProviderWithContract(t *testing.T, contract map[string]string, monitoringYAML string) string {
	t.Helper()
	root := t.TempDir()
	writeFiles(t, root, map[string]string{
		"go.mod": "module example.com/provider\n\ngo 1.27.1\n\nrequire " + contractPath + " v0.1.0\n\nreplace " + contractPath + " => ./contract\n",
		"definition/provider.yaml": "name: test-provider\ncomponents:\n  engine:\n    type: pxc\n" +
			"componentTypes:\n  pxc:\n    kind: mysql\n",
		"definition/versions.yaml":   "componentTypes: {}\n",
		"definition/monitoring.yaml": monitoringYAML,
	})
	writeFiles(t, filepath.Join(root, "contract"), contract)
	return filepath.Join(root, "definition")
}

const pmmWithContract = `
integrations:
  pmm:
    authModes: [ServiceAccountToken]
    contractModule: ` + contractPath + `
`

// wantContractMonitoring is the monitoring spec published for
// pmmWithContract: the contract's schemas, closed at their roots.
const wantContractMonitoring = `
integrations:
  pmm:
    authModes: [ServiceAccountToken]
    destinationParametersSchema:
      openAPIV3Schema:
        type: object
        additionalProperties: false
        required: [url]
        properties:
          url:
            type: string
            pattern: ^https?://[^/?#@]+/?$
    instanceParametersSchema:
      openAPIV3Schema:
        type: object
        additionalProperties: false
        properties:
          resources:
            type: object
            additionalProperties: false
            properties:
              limits:
                type: object
                additionalProperties:
                  x-kubernetes-int-or-string: true
`

// generatedMonitoring runs generate for defDir and returns the published
// spec.monitoring as YAML.
func generatedMonitoring(t *testing.T, defDir string) string {
	t.Helper()
	chartDir := t.TempDir()
	writeFiles(t, chartDir, map[string]string{"Chart.yaml": "apiVersion: v2\nname: provider-test\nversion: 0.1.0\n"})
	require.NoError(t, Run(Options{DefinitionDir: defDir, ChartDir: chartDir}))

	data, err := os.ReadFile(filepath.Join(chartDir, "generated", "provider-spec.yaml"))
	require.NoError(t, err)
	var generated struct {
		Spec map[string]any `yaml:"spec"`
	}
	require.NoError(t, yaml.Unmarshal(data, &generated))
	got, err := yaml.Marshal(generated.Spec["monitoring"])
	require.NoError(t, err)
	return string(got)
}

func TestGeneratePublishesContractSchemas(t *testing.T) {
	t.Parallel()

	defDir := writeProviderWithContract(t, contractFiles(), pmmWithContract)
	assert.YAMLEq(t, wantContractMonitoring, generatedMonitoring(t, defDir))
}

func TestAssembleRejectsContractModules(t *testing.T) {
	t.Parallel()

	without := func(file string) map[string]string {
		files := contractFiles()
		delete(files, file)
		return files
	}
	with := func(file, content string) map[string]string {
		files := contractFiles()
		files[file] = content
		return files
	}

	tests := map[string]struct {
		contract       map[string]string
		monitoringYAML string
		wantErrs       []string
	}{
		"module the provider does not require": {
			contract:       contractFiles(),
			monitoringYAML: "integrations: {pmm: {authModes: [ServiceAccountToken], contractModule: example.com/other}}",
			wantErrs: []string{
				`integrations["pmm"].contractModule: example.com/other: module example.com/other: not a known dependency`,
				`the provider's go.mod must require the contract module (go get example.com/other@<version>)`,
			},
		},
		"not a module path": {
			contract:       contractFiles(),
			monitoringYAML: "integrations: {pmm: {authModes: [ServiceAccountToken], contractModule: -mod=mod}}",
			wantErrs:       []string{`integrations["pmm"].contractModule: "-mod=mod" is not a module path`},
		},
		"no schema files": {
			contract:       map[string]string{"go.mod": "module " + contractPath + "\n"},
			monitoringYAML: pmmWithContract,
			wantErrs: []string{
				`integrations["pmm"].contractModule: example.com/pmm/api has no zz_generated.destination-parameters.yaml at its root`,
				`example.com/pmm/api has no zz_generated.instance-parameters.yaml at its root`,
			},
		},
		"no instance schema": {
			contract:       without(instanceParametersFile),
			monitoringYAML: pmmWithContract,
			wantErrs:       []string{`example.com/pmm/api has no zz_generated.instance-parameters.yaml at its root`},
		},
		"schema that is not a schema": {
			contract:       with(destinationParametersFile, "type: object\nproperty: {}\n"),
			monitoringYAML: pmmWithContract,
			wantErrs:       []string{`example.com/pmm/api: zz_generated.destination-parameters.yaml is not an OpenAPI v3 schema`, `unknown field "property"`},
		},
		"schema of something other than an object": {
			contract:       with(instanceParametersFile, "type: string\n"),
			monitoringYAML: pmmWithContract,
			wantErrs:       []string{`zz_generated.instance-parameters.yaml: parameters are an object, the schema has type "string"`},
		},
		"schemas written in monitoring.yaml": {
			contract: contractFiles(),
			monitoringYAML: `
integrations:
  pmm:
    authModes: [ServiceAccountToken]
    destinationParametersSchema: {openAPIV3Schema: {type: object}}
`,
			wantErrs: []string{`integrations["pmm"]: destinationParametersSchema and instanceParametersSchema are generated from the contract module; declare contractModule instead`},
		},
		"contract problems reported with the others": {
			contract:       without(destinationParametersFile),
			monitoringYAML: "integrations: {pmm: {contractModule: " + contractPath + "}}",
			wantErrs: []string{
				`integrations["pmm"].authModes: required`,
				`example.com/pmm/api has no zz_generated.destination-parameters.yaml at its root`,
			},
		},
	}
	for name, tt := range tests {
		t.Run(name, func(t *testing.T) {
			t.Parallel()

			_, err := Assemble(writeProviderWithContract(t, tt.contract, tt.monitoringYAML))
			require.Error(t, err)
			for _, want := range tt.wantErrs {
				assert.ErrorContains(t, err, want)
			}
		})
	}
}

// TestGenerateDownloadsContractModule covers a contract module the provider
// requires but has not downloaded yet, as when generate runs before the
// provider is built: it is fetched from the module proxy into the module
// cache. The proxy is a directory and the module cache empty.
func TestGenerateDownloadsContractModule(t *testing.T) {
	root := t.TempDir()
	proxy := filepath.Join(root, "proxy")
	version := module.Version{Path: contractPath, Version: "v0.1.0"}
	gomod := contractFiles()["go.mod"]

	source := filepath.Join(root, "source")
	writeFiles(t, source, contractFiles())
	versions := filepath.Join(proxy, contractPath, "@v")
	writeFiles(t, versions, map[string]string{
		"list":                    version.Version + "\n",
		version.Version + ".info": `{"Version":"` + version.Version + `","Time":"2026-01-01T00:00:00Z"}`,
		version.Version + ".mod":  gomod,
	})
	zipPath := filepath.Join(versions, version.Version+".zip")
	zipFile, err := os.Create(zipPath)
	require.NoError(t, err)
	require.NoError(t, modzip.CreateFromDir(zipFile, version, source))
	require.NoError(t, zipFile.Close())

	zipHash, err := dirhash.HashZip(zipPath, dirhash.Hash1)
	require.NoError(t, err)
	modHash, err := dirhash.Hash1([]string{"go.mod"}, func(string) (io.ReadCloser, error) {
		return io.NopCloser(strings.NewReader(gomod)), nil
	})
	require.NoError(t, err)

	provider := filepath.Join(root, "provider")
	writeFiles(t, provider, map[string]string{
		"go.mod": "module example.com/provider\n\ngo 1.27.1\n\nrequire " + contractPath + " " + version.Version + "\n",
		"go.sum": fmt.Sprintf("%s %s %s\n%s %s/go.mod %s\n", contractPath, version.Version, zipHash, contractPath, version.Version, modHash),
		"definition/provider.yaml": "name: test-provider\ncomponents:\n  engine:\n    type: pxc\n" +
			"componentTypes:\n  pxc:\n    kind: mysql\n",
		"definition/versions.yaml":   "componentTypes: {}\n",
		"definition/monitoring.yaml": pmmWithContract,
	})

	t.Setenv("GOPROXY", "file://"+filepath.ToSlash(proxy))
	t.Setenv("GOMODCACHE", filepath.Join(root, "modcache"))
	t.Setenv("GOFLAGS", "-modcacherw")
	t.Setenv("GONOSUMDB", contractPath)
	t.Setenv("GOWORK", "off")

	assert.YAMLEq(t, wantContractMonitoring, generatedMonitoring(t, filepath.Join(provider, "definition")))
	assert.DirExists(t, filepath.Join(root, "modcache", "example.com", "pmm", "api@"+version.Version))
}

// TestMonitoringFileMirrorsProviderMonitoring fails when core adds a field to
// Provider.spec.monitoring that monitoring.yaml cannot carry yet.
func TestMonitoringFileMirrorsProviderMonitoring(t *testing.T) {
	t.Parallel()

	jsonNames := func(typ reflect.Type) []string {
		names := make([]string, 0, typ.NumField())
		for f := range typ.Fields() {
			name, _, _ := strings.Cut(f.Tag.Get("json"), ",")
			names = append(names, name)
		}
		return names
	}
	assert.ElementsMatch(t,
		jsonNames(reflect.TypeFor[corev1alpha1.ProviderMonitoring]()),
		jsonNames(reflect.TypeFor[monitoringFile]()),
	)
}
