package generate

import (
	"fmt"
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"strings"

	corev1alpha1 "github.com/openeverest/openeverest/v2/api/core/v1alpha1"
	"github.com/openeverest/openeverest/v2/contract"
	"github.com/openeverest/provider-sdk/internal/chartrender"
)

// CompatCheckFile is the chart template, under templates/, that fails the
// render on an OpenEverest that does not serve the chart's stamp.
const CompatCheckFile = "openeverest-compat-check.yaml"

// providersCRD is the CRD of the Provider, the root object of every
// provider chart.
var providersCRD = "providers." + corev1alpha1.GroupVersion.Group

// CompatCheck returns the content of CompatCheckFile for a chart that
// applies objects of the core CRDs crds.
func CompatCheck(crds []string) string {
	quoted := make([]string, len(crds))
	for i, crd := range crds {
		quoted[i] = strconv.Quote(crd)
	}
	return `{{- /* Code generated by provider-sdk generate. DO NOT EDIT. */ -}}
{{- /*
Fails the render, before anything is applied, when the OpenEverest in the
cluster does not serve the OpenEverest this chart is built for; see
openeverest.contract.check in _openeverest_contract.tpl. crds lists the CRDs
of the objects OpenEverest interprets that the chart applies.
*/ -}}
{{- include "openeverest.contract.check" (dict
  "root" .
  "stamp" (index .Chart.Annotations ` + strconv.Quote(contract.VersionAnnotation) + `)
  "crds" (list ` + strings.Join(quoted, " ") + `)
  "object" (dict "apiVersion" ` + strconv.Quote(corev1alpha1.GroupVersion.String()) + ` "kind" "Provider" "crd" ` + strconv.Quote(providersCRD) + ` "name" (.Values.provider | default dict).name)
) -}}
`
}

// writeCompatCheck writes CompatCheckFile into the chart in chartDir, for
// the core CRDs of the objects the chart applies with its default values,
// and of the Provider, which it always applies.
func writeCompatCheck(chartDir string) error {
	crds, err := appliedCRDs(chartDir)
	if err != nil {
		return err
	}
	file := filepath.Join(chartDir, "templates", CompatCheckFile)
	if err := os.WriteFile(file, []byte(CompatCheck(crds)), 0o644); err != nil {
		return fmt.Errorf("writing %s: %w", file, err)
	}
	fmt.Fprintf(os.Stderr, "Generated: %s\n", file)
	return nil
}

// appliedCRDs returns the core CRDs of the objects the chart in chartDir
// applies with its default values, as CheckedCRDs lists them. The check
// itself is not rendered: it would find no cluster anyway, and the copy in
// the chart may be from another provider-sdk.
func appliedCRDs(chartDir string) ([]string, error) {
	objects, err := chartrender.Render(chartDir, "templates/"+CompatCheckFile)
	if err != nil {
		return nil, fmt.Errorf("rendering the chart to find the objects OpenEverest interprets: %w", err)
	}
	return CheckedCRDs(objects), nil
}

// CheckedCRDs returns the core CRDs the check of a chart that renders
// objects reads: the Provider's, which the chart always applies, then those
// of the other objects OpenEverest interprets that its own templates render,
// sorted. A chart is only checked against the parts of OpenEverest it uses;
// the objects of its subcharts carry stamps of their own.
func CheckedCRDs(objects []chartrender.Object) []string {
	var crds []string
	for _, o := range objects {
		crd, ok := chartrender.CoreInterpreted[o.GroupKind]
		if ok && o.Own() && crd != providersCRD && !slices.Contains(crds, crd) {
			crds = append(crds, crd)
		}
	}
	slices.Sort(crds)
	return append([]string{providersCRD}, crds...)
}
